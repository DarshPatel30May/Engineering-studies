/**
 * Dense linear solver: Gaussian elimination with partial pivoting.
 * Returns null when the system is singular (e.g. an unstable truss).
 */
export function solveLinear(Ain: number[][], bin: number[]): number[] | null {
  const n = Ain.length;
  if (n === 0) return [];
  const A = Ain.map((r) => r.slice());
  const b = bin.slice();
  const scale = Math.max(1e-12, ...A.flat().map(Math.abs));
  for (let c = 0; c < n; c++) {
    let piv = c;
    for (let r = c + 1; r < n; r++) if (Math.abs(A[r][c]) > Math.abs(A[piv][c])) piv = r;
    if (Math.abs(A[piv][c]) < 1e-10 * scale) return null;
    [A[c], A[piv]] = [A[piv], A[c]];
    [b[c], b[piv]] = [b[piv], b[c]];
    for (let r = c + 1; r < n; r++) {
      const f = A[r][c] / A[c][c];
      if (f === 0) continue;
      for (let k = c; k < n; k++) A[r][k] -= f * A[c][k];
      b[r] -= f * b[c];
    }
  }
  const x = new Array<number>(n).fill(0);
  for (let r = n - 1; r >= 0; r--) {
    let s = b[r];
    for (let k = r + 1; k < n; k++) s -= A[r][k] * x[k];
    x[r] = s / A[r][r];
  }
  return x;
}
